"""Базовый класс для сущностей предметной области.

Класс BaseEntity собирает общее поведение объектов проекта:

- хранение идентификатора в защищённом атрибуте и доступ к нему
  через свойство id;
- преобразование объекта в словарь для JSON-файла;
- полиморфные методы describe() и render(), которые каждый класс
  предметной области переопределяет по-своему;
- строковое представление объекта и сравнение по идентификатору.

Наследование используется именно для повторно используемого кода:
Club, Topic, Event и Registration не копируют общие методы, а
переопределяют только те из них, которые относятся к их сущности.
"""

from typing import Any, Dict, Optional


class BaseEntity:
    """Общая основа для Club, Topic, Event и Registration."""

    #: Название сущности: используется в строковом представлении.
    KIND = "сущность"

    def __init__(self, entity_id: int) -> None:
        """Сохранить идентификатор сущности.

        Идентификатор хранится в защищённом атрибуте: изменять его
        напрямую нельзя, доступ выполняется через свойство id.
        """
        self._id = int(entity_id)

    @property
    def id(self) -> int:
        """Вернуть идентификатор сущности."""
        return self._id

    @id.setter
    def id(self, value: int) -> None:
        """Задать идентификатор сущности."""
        self._id = int(value)

    def to_dict(self) -> Dict[str, Any]:
        """Преобразовать объект в словарь для сохранения в JSON.

        Базовый класс возвращает только идентификатор: конкретные
        поля добавляет метод to_dict() наследника.
        """
        return {"id": self._id}

    def describe(self) -> str:
        """Вернуть короткое описание сущности в одну строку."""
        return f"{self.KIND} {self._id}"

    def render(self, context: Optional[Dict[str, Any]] = None) -> str:
        """Сформировать многострочную карточку сущности.

        Параметр context позволяет передать дополнительные данные
        вывода: например, число занятых мест для карточки события.
        Базовый класс использует только описание объекта.
        """
        return self.describe()

    def __str__(self) -> str:
        """Вернуть строковое представление объекта."""
        return self.describe()

    def __repr__(self) -> str:
        """Вернуть представление объекта для отладки."""
        return f"{type(self).__name__}(id={self._id})"

    def __eq__(self, other: object) -> bool:
        """Сравнить объекты: класс и идентификатор должны совпасть."""
        if not isinstance(other, BaseEntity):
            return NotImplemented
        return type(self) is type(other) and self._id == other._id

    def __hash__(self) -> int:
        """Вернуть хеш объекта: он позволяет хранить объекты в set."""
        return hash((type(self).__name__, self._id))
